// `bun run golden:regenerate` rebuilds the SDK test fixtures and the golden report
// from the backend's vendored raw floor, deterministically. Dev-only script: it
// reads and writes local files and lives outside src/, so the SDK stays pure.
//
// Rule (documented in tests/fixtures/PROVENANCE.md, which this script writes):
//   1. Take every row of backend/tests/fixtures/regime/raw-indicator-history.csv.gz.
//   2. Add the extras from regime-extras.json.gz, mapped spx -> SPX, eth -> ETH,
//      tbill3m -> TBILL3M.
//   3. Keep rows dated on or after CUT_DATE (2022-01-01).
//   4. Sort by date, then indicator name, bytewise. Add source = "fixture".
//   5. Write the CSV (trailing newline) and the JSON (compact, no trailing newline).
//   6. Regenerate tests/golden/regime-report.json from runRegime over that CSV.
// `--check` recomputes everything in memory and exits 1 if any file would change.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";
import { parseRawHistory, toHistory } from "../src/input/load.ts";
import { buildReport, runRegime } from "../src/run.ts";

const CUT_DATE = "2022-01-01";
const HERE = dirname(fileURLToPath(import.meta.url));
const SDK = join(HERE, "..");
const BACKEND_FIX = join(SDK, "..", "..", "backend", "tests", "fixtures", "regime");
const OUT = {
  csv: join(SDK, "tests/fixtures/raw-indicator-history.csv"),
  json: join(SDK, "tests/fixtures/raw-indicator-history.json"),
  prov: join(SDK, "tests/fixtures/PROVENANCE.md"),
  golden: join(SDK, "tests/golden/regime-report.json"),
};
// Not generated here: the 8-year as-of fixture (issue 1399) is a public API
// pull, committed as is. This script only records its hash in PROVENANCE.md.
const FIXTURE_8Y = join(SDK, "tests/fixtures/allocate/raw-indicator-history-8y.csv");
// Not generated here either: the engine's weekly inputs and the prototype's
// weekly weights (issue 1403). This script only records their hashes.
const ENGINE_FIXTURES = ["engine-inputs.csv", "engine-weights-E1.csv", "engine-weights-E3.csv"];
const EXTRAS: Array<[key: "spx" | "eth" | "tbill3m", id: string]> = [
  ["spx", "SPX"],
  ["eth", "ETH"],
  ["tbill3m", "TBILL3M"],
];

const sha = (b: Buffer | string) => createHash("sha256").update(b).digest("hex");
const cmp = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

const rawGz = readFileSync(join(BACKEND_FIX, "raw-indicator-history.csv.gz"));
const extrasGz = readFileSync(join(BACKEND_FIX, "regime-extras.json.gz"));
const floorLines = gunzipSync(rawGz).toString("utf8").split("\n").slice(1).filter(Boolean);
const extras = JSON.parse(gunzipSync(extrasGz).toString("utf8")) as Record<string, Array<{ date: string; value: number }>>;

type Row = { date: string; indicator: string; value: string };
const rows: Row[] = [];
for (const line of floorLines) {
  const [date, indicator, value] = line.split(",");
  rows.push({ date, indicator, value });
}
for (const [key, id] of EXTRAS) for (const r of extras[key]) rows.push({ date: r.date, indicator: id, value: String(r.value) });
const kept = rows.filter((r) => r.date >= CUT_DATE);
kept.sort((a, b) => cmp(a.date, b.date) || cmp(a.indicator, b.indicator));
const dup = kept.findIndex((r, i) => i > 0 && r.date === kept[i - 1].date && r.indicator === kept[i - 1].indicator);
if (dup >= 0) throw new Error(`duplicate (date, indicator) at ${kept[dup].date} ${kept[dup].indicator}`);

const csv = "date,indicator,value,source\n" + kept.map((r) => `${r.date},${r.indicator},${r.value},fixture`).join("\n") + "\n";
const json = JSON.stringify(kept.map((r) => ({ date: r.date, indicator: r.indicator, value: Number(r.value), source: "fixture" })));

const report = buildReport(runRegime(toHistory(parseRawHistory(csv))));
const golden = JSON.stringify(report, null, 2) + "\n";

const perId: Record<string, number> = {};
for (const r of kept) perId[r.indicator] = (perId[r.indicator] ?? 0) + 1;
const ids = Object.keys(perId).sort(cmp);
const lastDate = kept[kept.length - 1].date;

const csv8y = readFileSync(FIXTURE_8Y, "utf8");
const engineHashes = ENGINE_FIXTURES.map((f) => `- \`allocate/${f}\` sha256 \`${sha(readFileSync(join(SDK, "tests/fixtures/allocate", f), "utf8"))}\`.`).join("\n");
const rows8y = csv8y.split("\n").slice(1).filter(Boolean).map((l) => l.split(",")[0]!).sort(cmp);

const prov = `# Fixture provenance

Generated by \`bun run golden:regenerate\` (packages/analyst-sdk/scripts/golden-regenerate.ts). Do not edit by hand.

## Source

- \`backend/tests/fixtures/regime/raw-indicator-history.csv.gz\`, sha256 \`${sha(rawGz)}\`, ${floorLines.length} rows.
- \`backend/tests/fixtures/regime/regime-extras.json.gz\`, sha256 \`${sha(extrasGz)}\`, rows: ${EXTRAS.map(([k, id]) => `${k} -> ${id} ${extras[k].length}`).join(", ")}.

## Rule

1. Take every row of the raw floor and add the extras, mapped spx to SPX, eth to ETH and tbill3m to TBILL3M.
2. Keep rows dated on or after the cut date ${CUT_DATE}.
3. Sort by date, then by indicator name (bytewise). Set \`source\` to \`fixture\` on every row.
4. CSV: header \`date,indicator,value,source\`, trailing newline. JSON: compact array of the same rows, no trailing newline. Values are copied as the source text (extras use the JS number string).
5. The golden \`tests/golden/regime-report.json\` is the default \`buildReport(runRegime(...))\` output over the CSV. It is cross-checked against the original JS reference by \`backend/tests/analyst-sdk-golden-reference.test.ts\`.

The rule reproduces the fixture committed before this script existed exactly, as a row set and in byte layout.

## Output

- Cut date: ${CUT_DATE}. Last date: ${lastDate}. Indicators: ${ids.length}.
- Rows: ${kept.length}.
- \`raw-indicator-history.csv\` sha256 \`${sha(csv)}\`.
- \`raw-indicator-history.json\` sha256 \`${sha(json)}\`.
- \`../golden/regime-report.json\` sha256 \`${sha(golden)}\`.

| indicator | rows |
| --- | ---: |
${ids.map((i) => `| ${i} | ${perId[i]} |`).join("\n")}

## allocate/raw-indicator-history-8y.csv (issue 1399)

Not generated by this script; it records the hash only. The 8-year input behind the as-of label test (\`tests/asof-labels.test.ts\`) and the published hindsight count of the allocation prototype (draft PR 1397): 1 of 419 weekly as-of labels differs from one full-history run, Oct 2018 to Oct 2026.

- Source: the public analytics API, \`https://robotmoney.network/api/public/analytics/raw-history?limit=1000\`, every page by \`nextCursor\`, the same pull as \`raw_history\` in PR 1397's \`scripts/allocate-data.py\`. Pulled 2026-10-23; the prototype's figure came from the 2026-10-20 pull. Rows are written in API order as \`date,indicator,value,source\`, the value as the JSON number's JS string.
- Cut: rows dated 2015-01-01 to 2026-10-07 inclusive. Every run in the test is as-of 2026-10-07 or earlier, so later rows never reach it. The earlier rows change nothing: all 419 as-of labels over the cut file are byte-identical to those over the uncut pull.
- Rows: ${rows8y.length}. First date: ${rows8y[0]}. Last date: ${rows8y[rows8y.length - 1]}.
- \`allocate/raw-indicator-history-8y.csv\` sha256 \`${sha(csv8y)}\`.

## allocate/engine-inputs.csv, engine-weights-E1.csv, engine-weights-E3.csv (issue 1403)

Not generated by this script; it records the hashes only. The prototype's weekly weights for the engine rules E1 and E3, which \`tests/engine.test.ts\` matches to 1e-9, and the inputs both engines read, for the 419 weekly decisions Oct 2018 to Oct 2026.

- \`engine-inputs.csv\`: one row per decision, \`date,asof,composite_pct,yield_<instrument>...,rv_BTC\`, numbers as JS round-trip strings, empty for null. \`composite_pct\` is \`asofLabels\` (issue 1399) over \`allocate/raw-indicator-history-8y.csv\` for \`decisionDates("2018-10-07", "2026-10-07")\`. The yields (30-day trailing mean of the daily APY) and \`rv_BTC\` (60 daily log returns ending on the as-of day, sample standard deviation x sqrt(365) x 100, empty before day 61) follow PR 1397's \`bin/allocate.ts\`, over its \`scripts/allocate-data.py\` pull of Yahoo and DefiLlama made 2026-10-24 (\`prices-8y.csv\`, sha256 \`b961037a08df56440bd50f78546a0d1a14d8c305fad56d5147ce2705a15b96b2\`). No copy of the prototype's 2026-10-20 pull exists.
- \`engine-weights-E1.csv\`, \`engine-weights-E3.csv\`: \`date,asof\` then the weight per holding, as JS round-trip strings. Regenerated by running the prototype's own \`engineWeights\` (PR 1397 head f101fbf5, \`src/allocate/engine.ts\`, unchanged) with its rule files \`rules/E1.json\` and \`rules/E3.json\` on the inputs above, with one change: the COMP cap is 10, not the prototype's 5. Caps come from the universe (\`universe/base-universe.json\` caps COMP at 10, with a compound group of 10); the universe's other groups (aave 35, bitcoin 10, gold 6) bind no tighter than the prototype's instrument caps. With the prototype's cap of 5, 141 E1 weeks and 138 E3 weeks would differ.
${engineHashes}

## Regenerate

\`\`\`
cd packages/analyst-sdk
bun run golden:regenerate          # rewrite fixtures, this file and the golden
bun run golden:regenerate --check  # exit 1 if any of them would change
\`\`\`
`;

const outputs: Array<[string, string]> = [[OUT.csv, csv], [OUT.json, json], [OUT.prov, prov], [OUT.golden, golden]];
if (process.argv.includes("--check")) {
  const stale = outputs.filter(([p, t]) => !existsSync(p) || readFileSync(p, "utf8") !== t).map(([p]) => p);
  if (stale.length) {
    console.error(`golden:regenerate --check: stale\n${stale.join("\n")}`);
    process.exit(1);
  }
  console.log("golden:regenerate --check: up to date");
} else {
  for (const [p, t] of outputs) writeFileSync(p, t);
  console.log(`wrote ${outputs.length} files, ${kept.length} rows, last date ${lastDate}`);
}
