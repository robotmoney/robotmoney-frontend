// The Investment Committee disclaimer, as ONE string every committee surface
// renders (Alpine factory `committeeDisclaimer`, registered in static-views.js).
//
// Why this exists: production robotmoney.net renders this block in the page
// body, above the footer, on /committee, on every session page and on every
// member page. This rebuild carried none of it — a content-parity sweep against
// production found zero occurrences of "automated content feed", "own research"
// or even the string "disclaim" anywhere under frontend/public/views/committee*.
// Look-and-feel is this repo's to change. This is not.
//
// The footer's existing line ("not a registered investment vehicle … not an
// offer of securities") is a statement about the PROTOCOL and is not a
// substitute: production carries both, and they answer different questions.
// This one answers four that nothing else on the site answers:
//   1. provenance — the feed is automated and the takes are written by AI
//   2. no advice  — none of it is advice, a recommendation or an endorsement
//   3. conflict   — a persona may hold the very thing it is arguing about
//   4. your call  — the reader is the one making the decision
// (3) is the highest-value line here. The committee pages print stances,
// confidence figures and a Committee Recommendation panel, and carry no other
// statement anywhere that a member may be talking its own book.
//
// The copy is production's, VERBATIM and deliberately so. Legal wording is not
// this repo's to improve, and paraphrasing a disclosure is how a claim quietly
// narrows. One string, four surfaces: editing it here changes all of them.
export const COMMITTEE_DISCLAIMER = [
  "The Robot Money Investment Committee is an automated content feed.",
  "Takes are generated by AI personas analyzing public information.",
  "Nothing here is financial advice, investment recommendation, or endorsement.",
  "Some personas hold positions in subjects they discuss; their manifests disclose what they hold.",
  "Always do your own research.",
].join(" ");
